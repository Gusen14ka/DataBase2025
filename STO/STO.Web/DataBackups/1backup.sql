CREATE TABLE IF NOT EXISTS "Cars" (
	"Id"	INTEGER NOT NULL,
	"CustomerId"	INTEGER NOT NULL,
	"EndService"	TEXT,
	"IsDeleted"	INTEGER NOT NULL DEFAULT 0,
	"ModelId"	INTEGER NOT NULL,
	"StartService"	TEXT NOT NULL DEFAULT '2024-01-01 12:00:00',
	"Vin"	INTEGER NOT NULL,
	"Year"	INTEGER NOT NULL,
	CONSTRAINT "PK_Cars" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Customers" (
	"Id"	INTEGER NOT NULL,
	"IsDeleted"	INTEGER NOT NULL,
	"FirstName"	TEXT NOT NULL,
	"LastName"	TEXT NOT NULL,
	"Email"	TEXT NOT NULL,
	"PhoneNumber"	TEXT NOT NULL,
	CONSTRAINT "PK_Customers" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Models" (
	"Id"	INTEGER NOT NULL,
	"Name"	TEXT NOT NULL,
	"Brand"	TEXT NOT NULL,
	CONSTRAINT "PK_Models" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "OrderParts" (
	"Id"	INTEGER NOT NULL,
	"OrderId"	INTEGER NOT NULL,
	"PartId"	INTEGER NOT NULL,
	"Quantity"	INTEGER NOT NULL,
	CONSTRAINT "PK_OrderParts" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "OrderServices" (
	"Id"	INTEGER NOT NULL,
	"OrderId"	INTEGER NOT NULL,
	"ServiceId"	INTEGER NOT NULL,
	"Quantity"	INTEGER NOT NULL,
	CONSTRAINT "PK_OrderServices" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Orders" (
	"Id"	INTEGER NOT NULL,
	"CarId"	INTEGER NOT NULL,
	"CreatedTime"	TEXT NOT NULL DEFAULT '2024-01-01 12:00:00',
	"CustomerId"	INTEGER NOT NULL,
	"FinishedTime"	TEXT,
	"IsFinished"	INTEGER NOT NULL DEFAULT 0,
	"Speedometer"	INTEGER NOT NULL,
	CONSTRAINT "PK_Orders" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "PartModelCompatibilities" (
	"PartId"	INTEGER NOT NULL,
	"ModelId"	INTEGER NOT NULL,
	CONSTRAINT "PK_PartModelCompatibilities" PRIMARY KEY("PartId","ModelId"),
	CONSTRAINT "FK_PartModelCompatibilities_Models_ModelId" FOREIGN KEY("ModelId") REFERENCES "Models"("Id") ON DELETE CASCADE,
	CONSTRAINT "FK_PartModelCompatibilities_Parts_PartId" FOREIGN KEY("PartId") REFERENCES "Parts"("Id") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Parts" (
	"Id"	INTEGER NOT NULL,
	"Name"	TEXT NOT NULL,
	"Price"	INTEGER NOT NULL,
	"Quantity"	INTEGER NOT NULL,
	"IsNew"	INTEGER NOT NULL,
	CONSTRAINT "PK_Parts" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "ServicePartAssociations" (
	"ServiceId"	INTEGER NOT NULL,
	"PartId"	INTEGER NOT NULL,
	CONSTRAINT "PK_ServicePartAssociations" PRIMARY KEY("ServiceId","PartId"),
	CONSTRAINT "FK_ServicePartAssociations_Parts_PartId" FOREIGN KEY("PartId") REFERENCES "Parts"("Id") ON DELETE CASCADE,
	CONSTRAINT "FK_ServicePartAssociations_Services_ServiceId" FOREIGN KEY("ServiceId") REFERENCES "Services"("Id") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Services" (
	"Id"	INTEGER NOT NULL,
	"Name"	TEXT NOT NULL,
	"Price"	INTEGER NOT NULL,
	"NextVisit"	TEXT,
	CONSTRAINT "PK_Services" PRIMARY KEY("Id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Timetables" (
	"CarId"	INTEGER NOT NULL,
	"ServiceId"	INTEGER NOT NULL,
	"NextVisit"	TEXT NOT NULL,
	CONSTRAINT "PK_Timetables" PRIMARY KEY("CarId","ServiceId"),
	CONSTRAINT "FK_Timetables_Cars_CarId" FOREIGN KEY("CarId") REFERENCES "Cars"("Id") ON DELETE CASCADE,
	CONSTRAINT "FK_Timetables_Services_ServiceId" FOREIGN KEY("ServiceId") REFERENCES "Services"("Id") ON DELETE CASCADE
);
